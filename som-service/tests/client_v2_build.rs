use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
    time::SystemTime,
};

#[test]
fn v2_client_crate_builds_offline() {
    let nonce = SystemTime::now()
        .duration_since(SystemTime::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let scratch = std::env::var_os("SOM_CLIENT_TEST_ROOT")
        .map(PathBuf::from)
        .unwrap_or_else(std::env::temp_dir);
    let root = scratch.join(format!(
        "som-client-v2-build-{}-{nonce}",
        std::process::id()
    ));
    let client = root.join("client");
    let prompt: serde_json::Value =
        serde_json::from_str(include_str!("fixtures/defer-four.prompt.json")).unwrap();
    let bundle = som_service::compile_prompt_v2(&prompt).unwrap();
    let files = som_service::assemble(&bundle).unwrap();
    assert!(
        files.contains_key("src/client.rs"),
        "the assembled crate has no generated client"
    );
    for (path, content) in &files {
        let path = client.join(path);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, content).unwrap();
    }
    let target = std::env::var_os("SOM_CLIENT_TEST_TARGET")
        .map(PathBuf::from)
        .unwrap_or_else(|| root.join("target"));
    let output = Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
        .current_dir(&client)
        .env("CARGO_TARGET_DIR", &target)
        .args(["build", "--locked", "--offline"])
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "cargo build --locked --offline failed in {}\nstdout:\n{}\nstderr:\n{}",
        client.display(),
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr),
    );
}

#[test]
fn v2_client_has_the_openapi_codegen_header() {
    let bundle = som_service::compile_prompt_v2(
        &serde_json::from_str(include_str!("fixtures/defer-four.prompt.json")).unwrap(),
    )
    .unwrap();
    let files = som_service::assemble(&bundle).unwrap();
    const HEADER: &str = "// Code generated by openapi-codegen. DO NOT EDIT.";
    for path in ["src/client.rs", "src/models.rs"] {
        let content = files.get(path).unwrap_or_else(|| panic!("missing {path}"));
        assert!(
            content.starts_with(HEADER),
            "{path} starts with {:?}",
            content.lines().next()
        );
    }

    let needle = concat!("lib", "_v2");
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    for directory in ["src", "templates", "tests"] {
        scan(&manifest.join(directory), needle);
    }
}

fn scan(directory: &Path, needle: &str) {
    for entry in fs::read_dir(directory).unwrap() {
        let path = entry.unwrap().path();
        if path.is_dir() {
            scan(&path, needle);
        } else if let Ok(text) = fs::read_to_string(&path) {
            assert!(
                !text.contains(needle),
                "{} still names {needle}",
                path.display()
            );
        }
    }
}
