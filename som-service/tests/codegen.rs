use serde_json::{Value, json};
use som_service::codegen::generate_client;

fn four_dsl() -> Value {
    serde_json::from_str(include_str!("fixtures/defer-four.dsl.json")).unwrap()
}

fn names(dsl: &Value) -> Vec<String> {
    dsl["operations"]
        .as_array()
        .unwrap()
        .iter()
        .map(|op| op["name"].as_str().unwrap().to_owned())
        .collect()
}

fn manifest(files: &std::collections::BTreeMap<String, String>) -> Value {
    serde_json::from_str(&files[".openapi-codegen.json"]).unwrap()
}

#[test]
fn client_is_generated_by_openapi_codegen() {
    let dsl = four_dsl();
    let files = generate_client(&dsl).unwrap();

    let keys: Vec<&str> = files.keys().map(String::as_str).collect();
    assert_eq!(
        keys,
        [
            ".openapi-codegen.json",
            "src/client.rs",
            "src/lib.rs",
            "src/models.rs"
        ]
    );

    let client = &files["src/client.rs"];
    assert!(client.starts_with("// Code generated by openapi-codegen. DO NOT EDIT."));
    assert!(client.contains("pub fn task_status("));
    assert!(client.contains("pub fn task_create("));
    assert!(client.contains("pub fn queue_put("));
    assert!(client.contains("pub fn task_cancel("));

    let lib = &files["src/lib.rs"];
    assert!(lib.contains("pub mod models;"));
    assert!(lib.contains("pub mod client;"));

    let manifest = manifest(&files);
    assert_eq!(manifest["generator"], "openapi-codegen");
    assert_eq!(manifest["target"], "rust-2024");
    assert_eq!(manifest["operations"], json!(names(&dsl)));
}

#[test]
fn generate_client_keeps_the_dsl_operation_order() {
    let mut dsl = four_dsl();
    dsl["operations"].as_array_mut().unwrap().reverse();
    let expected = names(&dsl);
    assert_eq!(
        expected,
        ["task_cancel", "queue_put", "task_create", "task_status"]
    );

    let files = generate_client(&dsl).unwrap();

    assert_eq!(manifest(&files)["operations"], json!(expected));
}

#[test]
fn generate_client_rejects_an_unknown_operation() {
    let mut dsl = four_dsl();
    dsl["operations"][0]["name"] = json!("no_such_operation");
    let error = generate_client(&dsl).unwrap_err();
    assert_eq!(error.status, 422, "{}", error.body);
    assert_eq!(
        error.body["code"], "UNSUPPORTED_OPERATION",
        "{}",
        error.body
    );

    let mut empty = four_dsl();
    empty["operations"] = json!([]);
    let error = generate_client(&empty).unwrap_err();
    assert_eq!(error.status, 400, "{}", error.body);
    assert_eq!(error.body["code"], "INVALID_SCHEMA", "{}", error.body);
}
