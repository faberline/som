"""Write measured candidate status without changing models or prior records."""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EVAL = ROOT / 'som-rs/evals/composable-2026-10-01'


def read(name):
    return json.loads((EVAL / name).read_text())


def p95(values):
    return sorted(values)[math.ceil(len(values) * 0.95) - 1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--kit', choices=('codex', 'codex-r2', 'codex-r3'), default='codex')
    args = parser.parse_args()
    if args.output.exists():
        raise ValueError('preserve existing report; choose a new output')
    gate = read('candidate-correctness.json')
    runtime, token, data = (read(name) for name in
        ('runtime-2/result.json', args.kit + '/results.json', 'data-audit-3.json'))
    protocol = read(args.kit + '/protocol-observations.json')
    dependencies = read(args.kit + '/dependency-observations.json')
    assert dependencies['same_provided_pins'] and dependencies['all_present_contract_versions_match']
    manifest_path = ROOT / 'som-rs/models/composed-candidate/manifest.json'
    manifest = json.loads(manifest_path.read_text())
    assert hashlib.sha256(manifest_path.read_bytes()).hexdigest() == gate['model_manifest_sha256']
    approved = gate['passed'] and token['passed']
    lines = ['# Composable SOM candidate result', '',
        f'Codex round: `{args.kit}`. All pairs in this report belong to that one sealed round.', '',
        f'Candidate correctness: **{gate["passed"]}**.',
        f'Codex token and complete-service gate: **{token["passed"]}**.',
        f'Candidate acceptance for this round: **{approved}**.', '',
        '`current` is unchanged. Claude and real cloud checks remain pending.',
        'This work does not release or deploy a service.', '',
        '## What changed', '',
        '- v6 expresses typed resources, capabilities and 1–11 semantic operations.',
        '- The model emits the complete block plan. Rust retains every choice and reference.',
        '- Typed block contracts reject missing permissions, transactions, dependencies and operations.',
        '- Legacy formats use the unchanged bundled decoder. Failed v6 plans are never repaired.',
        '- One evaluation call generates, places, prints and checks a complete service.',
        '- Actual native tool records prove complete response visibility for each delivery.', '',
        '## Correctness', '',
        '| Check | Result | Evidence |', '|---|---:|---|',
        '| Original PostgreSQL regression | 100/100 | `legacy-postgres-2/result.json` |',
        '| Existing complete services through Rust | 14/14 | `rust-services.json` |',
        '| Diagnostic compositions | 120/120 | `reference-compositions-3.json` |',
        '| Fresh compositions through Rust | 80/80 | `rust-blind.json` |',
        '| Actual Rust generation and Python byte parity | 528/528 | `runtime-2/result.json` |',
        '| HTTP rejection categories | 28/28 | `runtime-2/result.json` |',
        '| Static valid-plan parity | 20,734/20,734 | `parity-4.json` |',
        '| Deliberate invalid-plan categories | 25/25 | `parity-4.json` |',
        '| Python suite | 215 tests + 10 subtests | `python-tests.log` |',
        '| Latest focused boundary tests | 19/19 | `focused-tests.log` |',
        '| Rust suite | Passed | `rust-tests.log` |', '',
        'The 120 diagnostic services were fully checked from the Python reference.',
        'Their source is byte-identical to the current Rust output.',
        'The original 100 PostgreSQL checks also bind to identical current Rust source.',
        '`candidate-correctness.json` records every source and evidence hash.',
        'The 14 existing services and 80 fresh compositions were generated by the current Rust service before their complete behavior checks.', '',
        'Checks cover installation, real HTTP, field updates, queries, isolation, late transaction failure, recovery, races, identity, local object storage, workflows, restart and migrations where applicable.',
        'Each composition service result keeps its requirement hash, exact source hashes and full process and HTTP evidence.', '',
        '## Training and separation', '',
        f'The first perfect development checkpoint was step **{manifest["training_steps"]:,}**.',
        'All 600 full development sequences passed. Earlier checkpoints did not.',
        'The model uses two layers, width 64, four heads, seed 17, a 1,024-token vocabulary and a 4,096-token context.',
        'Both input and output have a 2,048-token limit.', '',
        '| Split | Services | App packages | Operations | Unique model inputs | Unique structures | Unique compositions |',
        '|---|---:|---:|---:|---:|---:|---:|']
    for name, row in data['groups'].items():
        lines.append(f'| {name} | {row["services"]:,} | {row["packages"]} | {row["operations"]:,} | {row["model_inputs"]:,} | {row["name_free_structures"]:,} | {row["compositions"]:,} |')
    lines += ['', 'Regression covers ten app families. Four boundary variants bring that group to fourteen packages.',
        'There is no split overlap in actual model input, name-free structure or full composition.',
        'Training covers all 95 selectable blocks, all 11 atomic operations and all 61 capability pairs.',
        'Experiment and document-review families stay out of training and development.',
        'The 120 earlier composition tests became diagnostic regression after a failed candidate.',
        'The fresh 80-case set was sealed separately. It did not select a checkpoint.', '',
        '| Trial | Last step | Trainer elapsed seconds | Outcome |', '|---|---:|---:|---|']
    elapsed = 0
    for trial in ('001', '002', '003'):
        prior = json.loads((EVAL / 'trials' / trial / 'model/manifest.json').read_text())
        elapsed += prior['elapsed_seconds']
        outcome = 'Development not perfect' if not prior['development_perfect'] else 'One composition rejected; trial not accepted'
        lines.append(f'| {trial} | {prior["training_steps"]:,} | {prior["elapsed_seconds"]:.2f} | {outcome} |')
    elapsed += manifest['elapsed_seconds']
    lines += [f'| 004 | {manifest["training_steps"]:,} | {manifest["elapsed_seconds"]:.2f} | Development and fresh test passed |', '',
        f'Recorded trainer time across these four trials: {elapsed:.2f} seconds.',
        'Failed trials, smoke probes and raw failures remain saved. No test result was substituted into a model answer.', '',
        '## Codex comparison', '',
        'Each app uses one fresh direct job and one fresh SOM job.',
        'The model is `gpt-6-astra`, high effort. Method order alternates by app.',
        'Both methods receive the same structured requirement, common contract, dependency pins and complete checker.',
        'Some direct jobs declare a subset of those libraries. The locked versions of the supplied libraries match the supplied pins.',
        f'See `{args.kit}/dependency-observations.json` for the exact dependency sets.',
        'Every CLI attempt, check, retry, contract read and full returned source counts.',
        'Totals cover the twenty benchmark jobs. Training, harness creation and delivery probes are separate setup work.',
        'Total tokens equal input plus output. Cached input is already included in input.',
        'One pair per app does not estimate run-to-run variance.', '',
        '| App | Direct tokens | SOM tokens | Saving | Passed |', '|---|---:|---:|---:|---|']
    for pair in token['pairs']:
        saving = 'unknown' if pair['saving_percent'] is None else f'{pair["saving_percent"]:.2f}%'
        lines.append(f'| {pair["app"]} | {pair["direct_tokens"]} | {pair["som_tokens"]} | {saving} | {pair["passed"]} |')
    failed = [pair for pair in token['pairs'] if not pair['passed']]
    if failed:
        lines += ['', '### Measured gaps', '',
                  '| App | Direct input | Direct output | SOM input | SOM output | Model requests, direct / SOM | Extra SOM tokens above the 30% target |',
                  '|---|---:|---:|---:|---:|---:|---:|']
        for pair in failed:
            modes = {row['mode']: row for row in token['results'] if row['app'] == pair['app']}
            direct, som = modes['direct'], modes['som']
            if not direct['usage'] or not som['usage']:
                lines.append(f'| {pair["app"]} | unknown | unknown | unknown | unknown | unknown | unknown |')
                continue
            gap = max(0, som['usage']['total_tokens'] - direct['usage']['total_tokens'] * 7 // 10)
            lines.append(f'| {pair["app"]} | {direct["usage"]["input_tokens"]:,} | {direct["usage"]["output_tokens"]:,} | {som["usage"]["input_tokens"]:,} | {som["usage"]["output_tokens"]:,} | {direct["model_requests"]} / {som["model_requests"]} | {gap:,} |')
        lines += ['', 'Input includes the request context, cached input and complete returned source.',
                  'The output reduction and the input difference together determine the total saving.',
                  'Equal model-request counts can leave a small total saving even when SOM removes most generated output tokens.',
                  'These observations do not replace the required total-token gate.']
    total = token['total_saving_percent']
    elapsed = {mode: sum(row['wall_seconds'] for row in token['results'] if row['mode'] == mode)
               for mode in ('direct', 'som')}
    requests = {mode: sum(row['model_requests'] for row in token['results'] if row['mode'] == mode)
                for mode in ('direct', 'som')}
    lines += ['', f'Aggregate direct tokens: {token["totals"]["direct"]}.',
              f'Aggregate SOM tokens: {token["totals"]["som"]}.',
              f'Aggregate saving: {total:.2f}%.' if total is not None else 'Aggregate saving: unknown.',
              'Each app and the aggregate must save at least 30%. Missing records cannot pass.',
              'Tool inspection and wait behavior also affect totals. These results measure the complete observed workflows.',
              f'The installed shell guard rejected {sum(row["counts"]["guard_rejections"] for row in protocol["jobs"])} tool calls. Their retries remain counted.',
              f'See `{args.kit}/results.md` for attempts, model requests, elapsed time and individual evidence checks.',
              'CLI cost and CLI round count remain blank because the CLI does not supply them.', '',
              '| Complete-job observation | Direct | SOM |',
              '|---|---:|---:|',
              f'| Elapsed seconds, all attempts | {elapsed["direct"]:.2f} | {elapsed["som"]:.2f} |',
              f'| Model requests | {requests["direct"]} | {requests["som"]} |',
              '| CLI rounds | | |',
              '| CLI reference cost | | |', '',
              f'Observed elapsed-time reduction: {(1 - elapsed["som"] / elapsed["direct"]) * 100:.2f}%.', '',
              '## Size, memory and elapsed time', '',
              '- Hardware: Apple M1 Max, 10 CPU cores and 64 GiB RAM. See `hardware-observation.json`.',
              f'- Complete model directory: {runtime["model_bytes"]:,} bytes.',
              f'- Idle resident memory: {runtime["idle_resident_bytes"]:,} bytes.',
              f'- Sampled peak resident memory: {runtime["peak_resident_bytes"]:,} bytes.',
              '- Memory was sampled every 20 ms during the measurement.',
              '- Each of three rounds starts with five warm-up requests.',
              '- Full elapsed time includes the request and parsing the complete HTTP response.',
              '- These observations are not hard acceptance limits.', '',
              '| Group | Round 1 p95 ms | Round 2 p95 ms | Round 3 p95 ms | Maximum |',
              '|---|---:|---:|---:|---:|']
    for name, values in runtime['p95_ms_by_round'].items():
        lines.append('| ' + name + ' | ' + ' | '.join(f'{value:.3f}' for value in (*values, max(values))) + ' |')
    phases = {'prompt validation': [], 'model inference': [], 'token decode and plan validation': [],
              'DSL validation': [], 'assembly': []}
    for row in runtime['performance']:
        if row['group'] == 'legacy100':
            continue
        for stage in row['stages']:
            mapping = ({'inference_ms': 'model inference', 'decode_validation_ms': 'token decode and plan validation'}
                       if stage['stage'] == 'model' else {'validation_ms': 'prompt validation',
                           'dsl_validation_ms': 'DSL validation', 'assembly_ms': 'assembly'})
            for key, label in mapping.items():
                phases[label].append(stage[key])
    lines += ['', '| v6 phase | Median ms | p95 ms |', '|---|---:|---:|']
    import statistics
    for name, values in phases.items():
        lines.append(f'| {name} | {statistics.median(values):.3f} | {p95(values):.3f} |')
    lines += ['', 'Phase quantiles are separate observations. They do not add up to total p95.', '',
              '| Standard service | Full request range ms | Source bytes |', '|---|---:|---:|']
    for index in range(14):
        rows = [row for row in runtime['performance'] if row['group'] == 'services14' and row['index'] == index]
        values = [row['milliseconds'] for row in rows]
        lines.append(f'| {rows[0]["app"]} | {min(values):.3f}–{max(values):.3f} | {rows[0]["source_bytes"]:,} |')
    lines += ['', '## Next action', '']
    if approved:
        lines.append('Keep this candidate available for Claude validation. Keep `current` unchanged until that separate work passes.')
    else:
        lines.append('Keep the current default. Review the failed app or missing evidence in the new Codex report before planning another sealed round.')
    lines += ['', 'Real Firebase, Google OAuth, S3 and GCS acceptance remains pending.',
              'Local provider tests do not claim real-cloud acceptance.']
    if args.kit == 'codex-r2':
        lines += ['', '## Prior round', '',
                  'Round 1 remains in `codex/` and `REPORT-r1.md`.',
                  'Round 2 uses clearer failure differences and a shared rule that removes directory discovery and repeated helper reads.',
                  'Both methods use the allowed file editor for source changes. No behavior assertion, model, block or token threshold changed.',
                  'The four diagnostic-boundary tests passed.',
                  'All twenty jobs ran again in fresh directories and sessions. No earlier result was selected to replace a new result.']
    if args.kit == 'codex-r3':
        interrupted = read('codex-r2/interruption-final.json')
        first = read('codex/results.json')
        prior_tokens = sum(first['totals'].values()) + interrupted['total_tokens']
        selected_total = (sum(token['totals'].values())
                          if all(isinstance(value, int) for value in token['totals'].values()) else None)
        combined = f'{prior_tokens + selected_total:,}' if selected_total is not None else 'unknown because some usage is missing'
        lines += ['', '## Earlier rounds and total measurement work', '',
                  'Round 1 completed twenty jobs. All services passed, but catalogs and recipes missed the token gate.',
                  'Its complete report remains in `REPORT-r1.md` and `codex/`.',
                  'Round 2 stopped after ten finished sessions. Provider cleanup hid the product response in a failure diagnostic.',
                  'The stopped runner was closed after its current child finished. All ten sessions and their usage remain saved.',
                  'The final child has no runner exit-status or wall-time receipt. Those values remain null.',
                  'The corrected diagnostic matches saved requests by method and path. It does not repeat a request.',
                  'Eleven focused tests passed. A replay of the real failure also showed the correct expected and actual timestamps.',
                  'See `recorded-diagnostic-tests-final.log`, `diagnostic-replay-final/result.json` and `codex-r2/interruption-final.json`.',
                  'Round 3 ran all twenty jobs in fresh directories and sessions. It reused no earlier job result.',
                  'The model, blocks, behavior assertions, dependency pins and 30 percent threshold did not change between these rounds.',
                  f'Total recorded tokens in the earlier twenty-job and interrupted ten-job rounds: {prior_tokens:,}.',
                  f'Total recorded tokens across all fifty measurement jobs: {combined}.',
                  'These combined costs are disclosed separately. Only the complete third round determines the reported acceptance result.']
    args.output.write_text('\n'.join(lines) + '\n')
    print(json.dumps({'report': str(args.output), 'candidate_accepted': approved}))


if __name__ == '__main__':
    main()
