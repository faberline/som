def encoded(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":")).encode()


def save(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(encoded(value))


class Reader:
    def __init__(self, repo):
        self.repo = repo

    def path(self, value, base=None):
        path = Path(value)
        path = path if path.is_absolute() else (base or self.repo) / path
        audit.need(path.is_relative_to(self.repo) and ".." not in path.parts, "unsafe fake path")
        return path

    def bytes(self, value):
        path = self.path(value)
        audit.need(path.is_file(), "missing fake raw file", "unrun")
        return path.read_bytes()

    def json(self, value):
        return json.loads(self.bytes(value))

    def hash(self, value):
        return audit.digest(self.bytes(value))


